// The default-seed known answer: 65536 draws from the documented default
// seed's stream-1 substream. Identical on every build, compiler, and CI
// run (pure integer arithmetic, ARCH-010).
TEST(SeededRandom, DefaultSeedKnownAnswer) {
  const u64 hash = seedCheck(laige::testing::kDefaultTestSeed,
                             kSeedCheckStreamId, "default");
  EXPECT_EQ(kKnownAnswerDefaultSeed, hash)
      << "default-seed stream changed (seed 0x1F055EED, stream "
      << kSeedCheckStreamId << ", " << kSeedCheckDraws << " draws); see the "
         "test-seed-check line above — re-pin the KAT only with a "
         "documented algorithm/seed change (docs/testing.md §4)";
  // Fast diagnostic: the first draws of the same stream.
  laige::Prng rng =
      laige::Prng::deriveSubstream(laige::testing::kDefaultTestSeed,
                                   kSeedCheckStreamId);
  for (int i = 0; i < 8; ++i) {
    EXPECT_EQ(kFirstDrawsStream1[i], rng.next_u64()) << "draw " << i;
  }
}

// One documented default seed repo-wide: the test default equals
// laige-fuzz's default (tools/fuzz/laige-fuzz.cpp kDefaultSeed).
TEST(SeededRandom, DefaultSeedMatchesTheFuzzRunnerSeed) {
  EXPECT_EQ(0x1F055EEDull, laige::testing::kDefaultTestSeed);
}

// The override path: LAIGE_TEST_SEED replaces the default, TestSeed()
// reports it, and the override-seed stream has its own committed KAT.
TEST(SeededRandom, SeedOverrideFromEnv) {
  ScopedTestSeedEnv scope(std::to_string(kOverrideSeed).c_str());
  // Decimal form, the accepted alternative to 0x-hex.
  EXPECT_EQ(kOverrideSeed, laige::testing::TestSeed());
  const u64 hash =
      seedCheck(kOverrideSeed, kOverrideStreamId, "override");
  EXPECT_EQ(kKnownAnswerOverrideSeed, hash)
      << "override-seed stream changed (seed 0x2468ACCE01234567, stream "
      << kOverrideStreamId << ", " << kSeedCheckDraws << " draws); see the "
         "test-seed-check line above";
}

// The invalid-env path of TestSeed(): a set-but-unparseable LAIGE_TEST_SEED
// records a loud failure with the offending value (CORE-008) and falls
// back to the default seed so the caller can complete its assertions.
TEST(SeededRandom, InvalidSeedEnvFailsLoudly) {
  ScopedTestSeedEnv scope("not-a-seed");
  u64 seed = 0;
  EXPECT_NONFATAL_FAILURE({ seed = laige::testing::TestSeed(); },
                          "LAIGE_TEST_SEED='not-a-seed' is not a valid seed");
  EXPECT_EQ(laige::testing::kDefaultTestSeed, seed);
}

// The seed parser accepts the documented forms and rejects the rest.
TEST(SeededRandom, SeedParserAcceptsDocumentedFormsOnly) {
  u64 v = 0;
  EXPECT_TRUE(laige::testing::ParseTestSeed("0x1F055EED", v));
  EXPECT_EQ(0x1F055EEDull, v);
  EXPECT_TRUE(laige::testing::ParseTestSeed("520445677", v));  // decimal form
  EXPECT_EQ(0x1F055EEDull, v);
  EXPECT_FALSE(laige::testing::ParseTestSeed("", v));
  EXPECT_FALSE(laige::testing::ParseTestSeed("0x", v));
  EXPECT_FALSE(laige::testing::ParseTestSeed("1F055EED", v));  // no 0x prefix
  EXPECT_FALSE(laige::testing::ParseTestSeed("0x1F055EEDx", v));  // trailing junk
  EXPECT_FALSE(laige::testing::ParseTestSeed("-1", v));  // negative
}

// Substream isolation sanity: two distinct substream ids of the same seed
// produce distinct streams (a collision would mean the derivation hash
// broke; the committed KATs above are the positive proof of determinism).
TEST(SeededRandom, DistinctSubstreamsDiverge) {
  u64 a[64] = {};
  u64 b[64] = {};
  laige::Prng ra =
      laige::Prng::deriveSubstream(laige::testing::kDefaultTestSeed,
                                   kSeedCheckStreamId);
  laige::Prng rb =
      laige::Prng::deriveSubstream(laige::testing::kDefaultTestSeed,
                                   kOverrideStreamId);
  for (int i = 0; i < 64; ++i) {
    a[i] = ra.next_u64();
    b[i] = rb.next_u64();
  }
  EXPECT_NE(fnv1a64(a, 64), fnv1a64(b, 64))
      << "substreams 1 and 2 of the default seed produced identical "
         "streams — the substream derivation is broken";
}

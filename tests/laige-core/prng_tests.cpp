TEST(PrngFloat01, First8KnownValues) {
  // KAT: the first 8 draws of kGoldenSeed, as their 24-bit mantissa k of
  // k * 2^-24 (float equality goes through double; dyadic => exact).
  // 2^-24 is the exact inverse of laige::Prng::kFloat01Unit.
  const u64 ks[8] = {7103266ull, 8440752ull, 12698639ull, 14265910ull,
                     7052825ull, 11703785ull, 12372555ull, 8552330ull};
  laige::Prng p(kGoldenSeed);
  for (int i = 0; i < 8; ++i) {
    const double v = static_cast<double>(p.next_float01());
    EXPECT_EQ(v, static_cast<double>(ks[i]) * 0x1.0p-24) << "draw " << i;
  }
}

TEST(PrngFloat01, DyadicAndInBounds) {
  // 2^24: the inverse scale of kFloat01Unit (24 mantissa bits).
  constexpr double kScale24 = 16777216.0;
  laige::Prng p(kGoldenSeed);
  double sum = 0.0;
  const int n = 1 << 16;
  for (int i = 0; i < n; ++i) {
    const float f = p.next_float01();
    const double v = static_cast<double>(f);
    EXPECT_GE(v, 0.0) << "draw " << i;
    EXPECT_LT(v, 1.0) << "draw " << i;
    // Exactly k * 2^-24: v * 2^24 is an integer (v < 1 => v*2^24 < 2^24,
    // exactly representable in double).
    const double scaled = v * kScale24;
    EXPECT_EQ(scaled, std::floor(scaled)) << "draw " << i;
    sum += v;
  }
  // Mean of 2^16 draws: expected 0.5, std ~ 0.00356; tolerance ~ 14 sigma.
  EXPECT_GT(sum / n, 0.45);
  EXPECT_LT(sum / n, 0.55);
}


TEST(PrngSubstreams, StreamsDoNotOverlap) {
  // Independence sanity: 2^16 draws from two different substreams share
  // no value. (Both streams sit on the single period-2^128-1 state cycle,
  // but their 2^16-draw windows are separated by ~2^112 cycle positions —
  // overlap is impossible for these seeds; the check is a KAT guard
  // against derivation collapse.)
  std::vector<u64> a(1 << 16), b(1 << 16);
  {
    laige::Prng sa = laige::Prng::deriveSubstream(kGoldenSeed, 1);
    laige::Prng sb = laige::Prng::deriveSubstream(kGoldenSeed, 2);
    for (auto& v : a) v = sa.next_u64();
    for (auto& v : b) v = sb.next_u64();
  }
  std::sort(a.begin(), a.end());
  std::sort(b.begin(), b.end());
  std::vector<u64> overlap;
  std::set_intersection(a.begin(), a.end(), b.begin(), b.end(),
                        std::back_inserter(overlap));
  EXPECT_TRUE(overlap.empty());
}


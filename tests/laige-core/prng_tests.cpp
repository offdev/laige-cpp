// FNV-1a 64-bit, big-endian byte order per u64 (endianness-independent),
// the same convention as the fpx16_16 determinism KAT (math_fixed_tests).
u64 fnv1a64(const u64* values, std::size_t n) {
  u64 h = 0xcbf29ce484222325ull;  // FNV offset basis (named: FNV-1a spec)
  for (std::size_t i = 0; i < n; ++i) {
    for (int shift = 56; shift >= 0; shift -= 8) {
      h ^= (values[i] >> shift) & 0xFFull;
      h *= 0x100000001b3ull;  // FNV prime (named: FNV-1a spec)
    }
  }
  return h;
}

// ---------------------------------------------------------------------------
// Independent reference (lemire/SIMDxorshift, xorshift128plus.c), inlined
// for the transcription check: the SAME algorithm written with the
// reference's own variable structure, so any drift in Prng::next_u64 or
// Prng::stepState shows up within a few steps.
// ---------------------------------------------------------------------------

u64 refNext(u64& p1, u64& p2) {
  const u64 s1 = p1 ^ (p1 << 23);
  const u64 s0 = p2;
  p1 = s0;
  p2 = s1 ^ s0 ^ (s1 >> 18) ^ (s0 >> 5);
  return p2 + s0;
}


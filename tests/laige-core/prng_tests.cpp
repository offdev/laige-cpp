namespace period_proof {

using u32 = std::uint32_t;
using u64 = std::uint64_t;

// GF(2)[x] polynomials: degree <= 255 in four little-endian 64-bit words
// (bit i is the coefficient of x^i); 512-bit workspaces for products.
struct Poly {
  u64 w[4] = {0, 0, 0, 0};
};
struct Big {
  u64 w[8] = {0, 0, 0, 0, 0, 0, 0, 0};
};

bool polyBit(const Poly& p, int i) {
  return ((p.w[i / 64] >> (i % 64)) & 1) != 0;
}

bool polyZero(const Poly& p) {
  return p.w[0] == 0 && p.w[1] == 0 && p.w[2] == 0 && p.w[3] == 0;
}

int polyDeg(const Poly& p) {
  for (int deg = 255; deg >= 0; --deg) {
    if (polyBit(p, deg)) return deg;
  }
  return -1;
}

int bigDeg(const Big& a) {
  for (int deg = 511; deg >= 0; --deg) {
    if (((a.w[deg / 64] >> (deg % 64)) & 1) != 0) return deg;
  }
  return -1;
}

// a ^= m << k (m a 256-bit Poly, k >= 0, i + k < 512 for every set bit).
void bigShiftXor(Big& a, const Poly& m, int k) {
  for (int i = 0; i < 256; ++i) {
    if (!polyBit(m, i)) continue;
    const int j = i + k;
    assert(j < 512);  // invariant of the callers (see BM, polyMod)
    a.w[j / 64] ^= 1ull << (j % 64);
  }
}

// Carryless (GF(2)) product: XOR of (b << i) for each set bit i of a.
// Integer multiplication would be WRONG (carries are not GF(2) addition).
Big polyMul(const Poly& a, const Poly& b) {
  Big r;
  for (int i = 0; i < 256; ++i) {
    if (!polyBit(a, i)) continue;
    bigShiftXor(r, b, i);
  }
  return r;
}

// a (a Big, < 512 bits) reduced modulo m (a 256-bit Poly, m != 0):
// long division over GF(2) — XOR of m shifted into each excess degree.
Poly polyMod(Big a, const Poly& m) {
  const int d = polyDeg(m);
  assert(d >= 0);
  for (;;) {
    const int deg = bigDeg(a);
    if (deg < d) break;
    bigShiftXor(a, m, deg - d);
  }
  Poly r;
  r.w[0] = a.w[0];
  r.w[1] = a.w[1];
  r.w[2] = a.w[2];
  r.w[3] = a.w[3];
  return r;
}

Poly polyMulmod(const Poly& a, const Poly& b, const Poly& m) {
  return polyMod(polyMul(a, b), m);
}

// x^exp mod m, exp a 192-bit little-endian word array (squaring-and-
// multiplying; every intermediate is reduced mod m).
Poly polyPowX(const u64 exp[3], const Poly& m) {
  Poly result;
  result.w[0] = 1;  // x^0
  Poly base;
  base.w[0] = 2;  // x^1
  for (int i = 0; i < 192; ++i) {
    if (((exp[i / 64] >> (i % 64)) & 1) != 0) {
      result = polyMulmod(result, base, m);
    }
    base = polyMulmod(base, base, m);
  }
  return result;
}

Poly polyGcd(Poly a, Poly b) {
  while (!polyZero(b)) {
    Big ba;
    ba.w[0] = a.w[0];
    ba.w[1] = a.w[1];
    ba.w[2] = a.w[2];
    ba.w[3] = a.w[3];
    a = b;
    b = polyMod(ba, b);
  }
  return a;
}

// Berlekamp-Massey over GF(2) on the first `count` probe bits: returns the
// shortest connection polynomial C (C[0] = 1 form: the recurrence is
// s[n] = sum_{i=1..L} C[i] s[n-i], L = final length) and its length L.
// Standard BM (Berlekamp 1967; Massey 1969); invariant: after n+1 samples,
// L <= (n+1)/2 and m + L <= n + 1, so x^m B has degree <= n <= 511 and
// stays inside the 512-bit workspace.
Poly bm(const u64* s, int count, int& L) {
  Poly C, B, T;
  C.w[0] = 1;
  B.w[0] = 1;
  L = 0;
  int m = 1;
  for (int n = 0; n < count; ++n) {
    u64 d = s[n] & 1;
    for (int i = 1; i <= L; ++i) {
      if (polyBit(C, i) && ((s[n - i] & 1) != 0)) d ^= 1;
    }
    if (d == 0) {
      ++m;
      continue;
    }
    T = C;
    Big xb;  // x^m B
    for (int i = 0; i < 256; ++i) {
      if (!polyBit(B, i)) continue;
      const int j = i + m;
      assert(j < 512);
      xb.w[j / 64] ^= 1ull << (j % 64);
    }
    for (int w = 0; w < 4; ++w) C.w[w] ^= xb.w[w];
    for (int w = 4; w < 8; ++w) {
      if (xb.w[w] != 0) {
        std::abort();  // unreachable by the BM invariant; fail loudly
      }
    }
    if (2 * L <= n) {
      L = n + 1 - L;
      B = T;
      m = 1;
    } else {
      ++m;
    }
  }
  assert(L <= 256);
  return C;
}

// Portable 64x64 -> 128 multiply (32-bit limbs; verified against __int128
// in the scratch harness before committing).
struct U128 {
  u64 lo, hi;
};

U128 mul128(u64 a, u64 b) {
  const u32 a0 = (u32)a, a1 = (u32)(a >> 32);
  const u32 b0 = (u32)b, b1 = (u32)(b >> 32);
  const u64 c0 = (u64)a0 * b0;
  const u64 c1 = (u64)a0 * b1;
  const u64 c2 = (u64)a1 * b0;
  const u64 c3 = (u64)a1 * b1;
  const u64 mid = (c0 >> 32) + (c1 & 0xFFFFFFFFu) + (c2 & 0xFFFFFFFFu);
  return {(c0 & 0xFFFFFFFFu) | (mid << 32),
          c3 + (c1 >> 32) + (c2 >> 32) + (mid >> 32)};
}

// 128-bit / 64-bit division, binary long division (remainder ignored;
// used only where the dividend is an exact multiple).
U128 div128By64(u64 nhi, u64 nlo, u64 d) {
  u64 qhi = 0, qlo = 0, rhi = 0, rlo = 0;
  for (int i = 127; i >= 0; --i) {
    const u64 bit = (i < 64) ? ((nlo >> i) & 1) : ((nhi >> (i - 64)) & 1);
    rhi = (rhi << 1) | (rlo >> 63);
    rlo = (rlo << 1) | bit;
    if (rhi != 0 || rlo >= d) {
      if (rlo >= d) {
        rlo -= d;
      } else {
        rlo += (0u - d);
        --rhi;
      }
      if (i < 64) qlo |= (1ull << i);
      else qhi |= (1ull << (i - 64));
    }
  }
  return {qlo, qhi};
}

// Miller-Rabin, deterministic for n < 3.3e24 with the twelve fixed bases
// (all moduli here are < 2^36; add-mod stays below 2^64 since 2m < 2^64).
u64 addMod(u64 x, u64 y, u64 m) {
  const u64 s = x + y;
  return s >= m ? s - m : s;
}

u64 modmul(u64 a, u64 b, u64 m) {
  u64 r = 0;
  while (b) {
    if (b & 1) r = addMod(r, a, m);
    a = addMod(a, a, m);
    b >>= 1;
  }
  return r;
}

u64 modpow(u64 a, u64 e, u64 m) {
  u64 r = 1;
  while (e) {
    if (e & 1) r = modmul(r, a, m);
    a = modmul(a, a, m);
    e >>= 1;
  }
  return r;
}

bool isPrime64(u64 n) {
  if (n < 2) return false;
  for (u64 p : {2u, 3u, 5u, 7u, 11u, 13u, 17u, 19u, 23u, 29u, 31u, 37u}) {
    if (n % p == 0) return n == p;
  }
  u64 d = n - 1;
  int r = 0;
  while ((d & 1) == 0) {
    d >>= 1;
    ++r;
  }
  for (u64 a : {2u, 3u, 5u, 7u, 11u, 13u, 17u, 19u, 23u, 29u, 31u, 37u}) {
    u64 x = modpow(a, d, n);
    if (x == 1 || x == n - 1) continue;
    bool ok = false;
    for (int i = 0; i < r - 1; ++i) {
      x = modmul(x, x, n);
      if (x == n - 1) {
        ok = true;
        break;
      }
    }
    if (!ok) return false;
  }
  return true;
}

}  // namespace period_proof

namespace {

// One coordinate of the state map A on (part1, part2) (the engine's step,
// exposed via Prng::stepState), sampled once per step from a starting
// state. The probe bit is a fixed nonzero linear observation of the
// state (the top bit of word 2); any fixed nonzero coordinate works —
// the linear complexity of the orbit is the same for all of them.
void probeStateMap(u64* s0, u64* s1, int count, std::vector<u64>* probe) {
  probe->resize(count);
  for (int t = 0; t < count; ++t) {
    (*probe)[t] = (*s1 >> 63) & 1;
    laige::Prng::stepState(*s0, *s1);
  }
}

}  // namespace

// The committed period proof: the state map's characteristic polynomial
// over GF(2) is the primitive polynomial of degree 128, so every
// nonzero state has period exactly 2^128 - 1 (hence the output stream
// has no short cycle). Method (CPP-014):
//   1. Probe the map from the basis state e0 = (1, 0) — a length-512
//      bit sequence p[t] of one coordinate of A^t e0.
//   2. Berlekamp-Massey finds the shortest recurrence C of p. For a
//      sequence whose linear complexity is exactly 128, BM converges
//      after 2*128 = 256 samples (512 are used for margin); the
//      recurrence is then re-verified over the whole probe.
//   3. C (stored as sum c_i x^i, satisfying p[t] = sum c_i p[t-i]) is
//      the RECIPROCAL of the state map's characteristic polynomial:
//      charpoly(A)(x) = x^128 C(1/x) = sum c_{128-i} x^i =: P. (The
//      recurrence relates p[t] to LOWER indices; the characteristic
//      polynomial annihilates A, whose powers move to HIGHER indices.)
//   4. P(A) = 0 is checked directly on all 128 basis states (Cayley-
//      Hamilton in the form we need): P monic of degree 128 = dim and
//      P(A) = 0 imply P = charpoly(A).
//   5. P is checked irreducible: x^(2^128) = x (mod P) and
//      gcd(x^(2^d) - x, P) = 1 for every proper divisor d of 128
//      (Ruffini's theorem over GF(2)).
//   6. P is checked primitive: P | x^(2^128-1) - 1 and P does not divide
//      x^((2^128-1)/q) - 1 for every prime q | 2^128 - 1. Primitivity
//      of the characteristic polynomial of an invertible linear map over
//      GF(2) is exactly "every nonzero state has maximal period".
//   (Primitives: 2^128 - 1 = product of the nine primes below — verified
//    here by portable 128-bit multiply and by Miller-Rabin.)
TEST(PrngPeriod, StateMapHasPrimitiveCharacteristicPolynomial) {
  using period_proof::Poly;
  using period_proof::U128;
  using namespace period_proof;

  // 1. Probe.
  u64 s0 = 1, s1 = 0;
  std::vector<u64> probe;
  probeStateMap(&s0, &s1, 512, &probe);
  u64 probeBits = 0;
  for (u64 bit : probe) probeBits |= bit;
  ASSERT_NE(probeBits, 0u);  // the observation is nonzero somewhere

  // 2. BM.
  int L = 0;
  const Poly C = bm(probe.data(), 512, L);
  ASSERT_EQ(L, 128);
  ASSERT_EQ(polyDeg(C), 128);
  ASSERT_TRUE(polyBit(C, 0));  // monic in the connection form

  // The recurrence reproduces the probe beyond the BM window (256..512):
  // if BM had a bug, this fails before any polynomial claim is made.
  for (int t = 128; t < 512; ++t) {
    u64 acc = 0;
    for (int i = 1; i <= 128; ++i) {
      if (polyBit(C, i) && ((probe[t - i] & 1) != 0)) acc ^= 1;
    }
    ASSERT_EQ(acc, probe[t] & 1) << "t " << t;
  }

  // 3. P = x^128 C(1/x).
  Poly P;
  for (int i = 0; i <= 128; ++i) {
    if (!polyBit(C, i)) continue;
    const int j = 128 - i;
    P.w[j / 64] |= 1ull << (j % 64);
  }
  ASSERT_EQ(polyDeg(P), 128);
  ASSERT_TRUE(polyBit(P, 128));

  // 4. P(A) = 0 on every basis state: for e_j, accumulate
  //    sum_i P_i A^i e_j (XOR) and require the zero state.
  for (int j = 0; j < 128; ++j) {
    u64 t0 = (j < 64) ? (1ull << j) : 0;
    u64 t1 = (j >= 64) ? (1ull << (j - 64)) : 0;
    u64 acc0 = 0, acc1 = 0;
    for (int i = 0; i <= 128; ++i) {
      if (polyBit(P, i)) {
        acc0 ^= t0;
        acc1 ^= t1;
      }
      laige::Prng::stepState(t0, t1);
    }
    ASSERT_EQ(acc0, 0u) << "basis " << j;
    ASSERT_EQ(acc1, 0u) << "basis " << j;
  }

  // 5. Irreducibility (Ruffini): x^(2^128) = x (mod P) and
  //    gcd(x^(2^d) - x, P) = 1 for d in {1,2,4,8,16,32,64}.
  u64 exp128[3] = {0, 0, 1};  // 2^128
  const Poly x128 = polyPowX(exp128, P);
  Poly x;
  x.w[0] = 2;
  ASSERT_TRUE(x128.w[0] == x.w[0] && x128.w[1] == x.w[1] &&
              x128.w[2] == x.w[2] && x128.w[3] == x.w[3]);
  const int divisors[] = {1, 2, 4, 8, 16, 32, 64};
  for (int d : divisors) {
    u64 exp[3] = {0, 0, 0};
    if (d == 64) exp[1] = 1;
    else exp[0] = 1ull << d;
    Poly diff = polyPowX(exp, P);
    diff.w[0] ^= 2;  // x^(2^d) - x  (GF(2): - == +)
    Poly g = polyGcd(diff, P);
    Poly one;
    one.w[0] = 1;
    ASSERT_TRUE(g.w[0] == 1 && g.w[1] == 0 && g.w[2] == 0 && g.w[3] == 0)
        << "d " << d;
  }

  // 6. Primitivity: P | x^(2^128-1) - 1, and no shorter q-th root.
  //    2^128 - 1 = 3 * 5 * 17 * 257 * 641 * 65537 * 6700417 * 274177 *
  //                67280421310721  (Fermat-prime + Aurifeuillean factors).
  const u64 kPrimesOf2128m1[] = {
      3ull, 5ull, 17ull, 257ull, 641ull, 65537ull,
      6700417ull, 274177ull, 67280421310721ull,
  };
  for (u64 q : kPrimesOf2128m1) {
    ASSERT_TRUE(isPrime64(q)) << "factor " << q;
  }
  u64 plo = 1, phi = 0;  // 128-bit product accumulator
  for (u64 q : kPrimesOf2128m1) {
    const U128 m1 = mul128(plo, q);
    const U128 m2 = mul128(phi, q);
    plo = m1.lo;
    phi = m1.hi + m2.lo;
  }
  ASSERT_EQ(plo, 0xFFFFFFFFFFFFFFFFull);
  ASSERT_EQ(phi, 0xFFFFFFFFFFFFFFFFull);  // product == 2^128 - 1

  Poly one;
  one.w[0] = 1;
  u64 expFull[3] = {0xFFFFFFFFFFFFFFFFull, 0xFFFFFFFFFFFFFFFFull, 0};
  const Poly full = polyPowX(expFull, P);
  ASSERT_TRUE(full.w[0] == 1 && full.w[1] == 0 && full.w[2] == 0 &&
              full.w[3] == 0);
  for (u64 q : kPrimesOf2128m1) {
    const U128 e =
        div128By64(0xFFFFFFFFFFFFFFFFull, 0xFFFFFFFFFFFFFFFFull, q);
    u64 expE[3] = {e.lo, e.hi, 0};
    const Poly shortCyc = polyPowX(expE, P);
    // x^((2^128-1)/q) != 1 (mod P): a primitive polynomial is a
    // generator of GF(2^128)^*, so no proper divisor of 2^128-1 works.
    const bool isOne = shortCyc.w[0] == 1 && shortCyc.w[1] == 0 &&
                       shortCyc.w[2] == 0 && shortCyc.w[3] == 0;
    ASSERT_FALSE(isOne) << "q " << q;
  }
  // Every step of the proof passed: every nonzero state has period
  // exactly 2^128 - 1.
  SUCCEED();
}

// Empirical screen (complements the proof; cheap, and would catch a
// *construction* bug that the algebra could in principle miss): 4M draws
// have no duplicate, and no period-q pattern for the small prime divisors
// of 2^128 - 1.
TEST(PrngPeriod, OutputStreamHasNoShortCycles) {
  laige::Prng p(kGoldenSeed);
  std::vector<u64> v(4096000);
  for (auto& x : v) x = p.next_u64();
  {
    std::vector<u64> sorted(v);
    std::sort(sorted.begin(), sorted.end());
    u64 dups = 0;
    for (std::size_t i = 1; i < sorted.size(); ++i) {
      if (sorted[i] == sorted[i - 1]) ++dups;
    }
    EXPECT_EQ(dups, 0u);
  }
  // If the stream had period q, every window position would repeat.
  // Deterministic KAT: exactly 0 matches in a 4096-position window.
  const u64 primes[] = {3ull, 5ull, 17ull, 257ull, 641ull, 65537ull,
                        274177ull, 6700417ull};
  const int kW = 4096;
  for (u64 q : primes) {
    laige::Prng pre(kGoldenSeed);
    std::vector<u64> window(kW);
    for (auto& x : window) x = pre.next_u64();
    laige::Prng p2(kGoldenSeed);
    for (u64 i = 0; i < q; ++i) p2.next_u64();
    u64 matches = 0;
    for (int i = 0; i < kW; ++i) {
      if (p2.next_u64() == window[i]) ++matches;
    }
    EXPECT_EQ(matches, 0u) << "q " << q;
  }
}

TEST(PrngRange, KnownValues) {
  // Each draw starts a fresh golden-seed stream (independent KATs).
  auto draw = [](u32 lo, u32 hi) {
    laige::Prng p(kGoldenSeed);
    return p.next_range(lo, hi);
  };
  EXPECT_EQ(draw(5, 9), 7u);
  EXPECT_EQ(draw(0, 7), 3u);
  EXPECT_EQ(draw(0, 1), 0u);
  EXPECT_EQ(draw(1000000, 2000000), 1190186u);
}

TEST(PrngRange, PowerOfTwoSpanUsesFastPath) {
  // n = 8 divides 2^64, so the result is exactly the low 3 bits of the
  // first draw — the rem == 0 branch, verified against the KAT.
  u64 first = 0;
  {
    laige::Prng p(kGoldenSeed);
    first = p.next_u64();
  }
  laige::Prng p(kGoldenSeed);
  EXPECT_EQ(p.next_range(0, 8), static_cast<u32>(first & 7u));
}

TEST(PrngRange, SpanOneAlwaysLow) {
  laige::Prng p(kGoldenSeed);
  for (int i = 0; i < 1000; ++i) {
    EXPECT_EQ(p.next_range(0xFFFFFFFEu, 0xFFFFFFFFu), 0xFFFFFFFEu);
    EXPECT_EQ(p.next_range(0u, 1u), 0u);
  }
}

TEST(PrngRange, DrawsStayInBounds) {
  laige::Prng p(kGoldenSeed);
  const u32 spans[] = {1, 2, 3, 7, 8, 255, 256, 65535, 65536, 1000001,
                       0xFFFFFFFFu};
  for (u32 span : spans) {
    laige::Prng q(kGoldenSeed + span);
    for (int i = 0; i < 10000; ++i) {
      const u32 v = q.next_range(0, span);
      EXPECT_LT(v, span) << "span " << span << " draw " << i;
    }
  }
}

TEST(PrngRange, Unbiased) {
  // 2^18 draws; the Lemire rejection makes the distribution exactly
  // uniform, so every bucket lands at its expectation within ~12 sigma
  // (tolerances below are ~17 sigma: no flake possible in practice, and
  // the seed is fixed anyway — deterministic KAT either way).
  {
    laige::Prng p(kGoldenSeed);
    u64 counts[8] = {0, 0, 0, 0, 0, 0, 0, 0};
    const int n = 1 << 18;
    for (int i = 0; i < n; ++i) {
      const u32 v = p.next_range(0, 8);
      ++counts[v];
    }
    const u64 expected = n / 8;  // 16384, std ~ 120
    for (u32 v = 0; v < 8; ++v) {
      EXPECT_GT(counts[v], expected - 2000) << "bucket " << v;
      EXPECT_LT(counts[v], expected + 2000) << "bucket " << v;
    }
  }
  {
    laige::Prng p(kGoldenSeed);
    u64 counts[3] = {0, 0, 0};
    const int n = 1 << 18;
    for (int i = 0; i < n; ++i) {
      const u32 v = p.next_range(0, 3);
      ++counts[v];
    }
    // expected 87381.33 per bucket, std ~ 241; tolerance ~ 10 sigma.
    for (u32 v = 0; v < 3; ++v) {
      EXPECT_GT(counts[v], 87381u - 2500) << "bucket " << v;
      EXPECT_LT(counts[v], 87381u + 2500) << "bucket " << v;
    }
  }
}


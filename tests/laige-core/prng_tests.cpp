TEST(PrngGolden, First32Match) {
  laige::Prng p(kGoldenSeed);
  for (int i = 0; i < 32; ++i) {
    EXPECT_EQ(p.next_u64(), kGoldenFirst32[i]) << "draw " << i;
  }
}

TEST(PrngGolden, FNV1aOfFirst4096) {
  laige::Prng p(kGoldenSeed);
  std::vector<u64> draws(4096);
  for (auto& d : draws) d = p.next_u64();
  // State hash of the first 4096 draws: the replay fixture (ARCH-010,
  // TEST-004). Fails if the algorithm changes — intentionally.
  EXPECT_EQ(fnv1a64(draws.data(), draws.size()), 0xB64E76173859B6D8ull);
}

TEST(PrngGolden, ReferenceMatch) {
  // Transcription check (10^4 consecutive outputs) against the inlined
  // reference, from a non-golden state so the KATs above cannot mask a
  // drift. The engine's output tap is the new second state word plus the
  // old second state word; the reference computes the same quantity in
  // its own variable structure.
  u64 e0 = 0xA5A5A5A5A5A5A5A5ull, e1 = 0x5A5A5A5A5A5A5A5Aull;
  u64 r0 = e0, r1 = e1;
  for (int i = 0; i < 10000; ++i) {
    const u64 refOut = refNext(r0, r1);
    const u64 old1 = e1;
    laige::Prng::stepState(e0, e1);
    const u64 engOut = e1 + old1;
    EXPECT_EQ(refOut, engOut) << "step " << i;
    EXPECT_EQ(r0, e0) << "step " << i;
    EXPECT_EQ(r1, e1) << "step " << i;
  }
}

TEST(PrngGolden, SeedStateNeverZero) {
  // splitmix64 is a bijection and its two seeding inputs differ by the
  // nonzero increment, so no seed reaches the excluded all-zero state.
  // Spot-check the first 100k seeds (fast; the proof is in the header).
  for (u64 seed = 0; seed < 100000; ++seed) {
    u64 s0 = 0, s1 = 0;
    laige::Prng::seedState(seed, s0, s1);
    EXPECT_TRUE(s0 != 0 || s1 != 0) << "seed " << seed;
  }
}

